// Package analysis provides the analysis phase data structures for the Chronocone Planning Language.
//
// The analysis phase transforms parser-level concept definitions into analysis-level
// structures optimized for validation and code generation. This includes building
// concept lookup maps, validating concept references, and resolving value generators.
//
// This file contains the core data structures for Increment 1: Basic Concept Definitions.
// See ERO001: Concepts Analysis Phase for the incremental implementation plan.
package analysis

import (
	"fmt"
	"strconv"

	"github.com/chronocone/chronocone_planning_language/src/main/go/ast"
	"github.com/chronocone/chronocone_planning_language/src/main/go/symboltable"
)

// AnalysisConceptValueDefinition represents a single concept value with its position.
//
// The Position field provides O(1) access to the value's order within the concept,
// which is essential for range operations and value ordering validation.
type AnalysisConceptValueDefinition struct {
	// Name is the string value of the concept (e.g., "USA", "Canada", "Mexico").
	Name string

	// Position is the zero-based index of this value within the concept's value list.
	// This enables O(1) position-based operations and range extraction.
	Position int
}

// Generator is the analysis-phase interface for concept value generators.
//
// Implementations of this interface generate the actual string values for a concept
// based on the parsed generator definition. The analysis phase uses this interface
// to abstract over different generator types (Values, IntRange, ConceptRange, etc.).
//
// For Increment 1, only ValuesGenerator is supported. Future increments will add
// IntRangeGenerator and ConceptRangeGenerator.
type Generator interface {
	// GenerateValues produces the concept values defined by this generator.
	//
	// The concepts parameter provides access to already-resolved concept definitions,
	// enabling generators like ConceptRangeGenerator to reference values from other
	// concepts.
	//
	// Parameters:
	//   - concepts: A map of concept names to their resolved definitions. This allows
	//     generators to reference other concepts (e.g., ConceptRangeGenerator).
	//
	// Returns:
	//   - A slice of string values generated by this generator, in the order they
	//     should appear in the concept's value list.
	//   - An error if value generation fails (e.g., referenced concept not found,
	//     invalid range bounds, etc.).
	GenerateValues(concepts map[string]AnalysisConceptDefinition) ([]string, error)
}

// ValuesGenerator generates values from an explicit list of value strings.
//
// This is the simplest generator type, used when a concept defines its values
// directly: Country=[Values[USA, Canada, Mexico]]
//
// The values are stored as-is and returned in the order they were declared.
type ValuesGenerator struct {
	// Values is the slice of string values to generate.
	// Each value appears in the order it was declared in the CPL source.
	Values []string
}

// GenerateValues returns the explicit values stored in this generator.
//
// For ValuesGenerator, this simply returns the pre-defined Values slice without
// any transformation. This method satisfies the Generator interface.
//
// Parameters:
//   - concepts: Ignored for ValuesGenerator (no external references needed),
//     but required to satisfy the Generator interface signature.
//
// Returns:
//   - The slice of string values in declaration order.
//   - Never returns an error for ValuesGenerator (always returns nil error).
func (v *ValuesGenerator) GenerateValues(concepts map[string]AnalysisConceptDefinition) ([]string, error) {
	return v.Values, nil
}

// IntRangeGenerator generates values from an integer range specification.
//
// This generator expands Int[Start, End, Step] into a sequence of string values,
// ordered from Start to End using the specified step increment. For example:
//   - Int[1, 12, 1] expands to ["1", "2", ..., "12"]
//   - Int[2, 10, 2] expands to ["2", "4", "6", "8", "10"]
//
// The step parameter controls the increment between values. Positive steps
// generate ascending sequences; negative steps generate descending sequences.
// A step of zero is invalid and will produce an error during value generation.
type IntRangeGenerator struct {
	// Start is the first integer value in the range (inclusive).
	Start int

	// End is the last integer value in the range (inclusive).
	End int

	// Step is the increment between consecutive values.
	// Must be non-zero. Positive for ascending, negative for descending.
	Step int
}

// MaxIntRangeValues limits the number of values an Int range can generate.
// This prevents memory exhaustion from accidentally large ranges.
const MaxIntRangeValues = 10000

// GenerateValues expands the integer range into a slice of string values.
//
// Values are generated from Start to End (inclusive) using the specified Step.
// For positive steps, generation stops when the value exceeds End.
// For negative steps, generation stops when the value is less than End.
//
// Parameters:
//   - concepts: Ignored for IntRangeGenerator (no external references needed),
//     but required to satisfy the Generator interface signature.
//
// Returns:
//   - A slice of string representations of the integers in the range,
//     in generation order.
//   - An error if the range parameters are invalid or would produce too many values.
func (irg *IntRangeGenerator) GenerateValues(concepts map[string]AnalysisConceptDefinition) ([]string, error) {
	if irg.Step == 0 {
		return nil, fmt.Errorf("step cannot be zero in Int range generator")
	}

	// Determine direction and validate bounds
	var count int
	if irg.Step > 0 {
		if irg.Start > irg.End {
			return nil, fmt.Errorf("start (%d) must be less than or equal to end (%d) when step is positive", irg.Start, irg.End)
		}
		count = (irg.End-irg.Start)/irg.Step + 1
	} else {
		if irg.Start < irg.End {
			return nil, fmt.Errorf("start (%d) must be greater than or equal to end (%d) when step is negative", irg.Start, irg.End)
		}
		count = (irg.Start-irg.End)/(-irg.Step) + 1
	}

	if count <= 0 {
		return []string{}, nil
	}

	if count > MaxIntRangeValues {
		return nil, fmt.Errorf("Int range would produce %d values, exceeding maximum of %d", count, MaxIntRangeValues)
	}

	values := make([]string, 0, count)
	if irg.Step > 0 {
		for i := irg.Start; i <= irg.End; i += irg.Step {
			values = append(values, strconv.Itoa(i))
		}
	} else {
		for i := irg.Start; i >= irg.End; i += irg.Step {
			values = append(values, strconv.Itoa(i))
		}
	}

	return values, nil
}

// ConceptRangeGenerator generates values by referencing a range from another concept.
//
// This generator expands Concept[ConceptName, StartValue, EndValue] into a sequence
// of string values by looking up the referenced concept and extracting the values
// from StartValue to EndValue (inclusive) in their original order.
//
// For example, if Country = [Values[USA, Canada, Mexico, UK, France]], then:
//   - Concept[Country, Canada, UK] expands to ["Canada", "Mexico", "UK"]
//
// The referenced concept must already be resolved in the concepts map.
type ConceptRangeGenerator struct {
	// ConceptName is the name of the source concept to reference.
	// This concept must exist in the concepts map and have resolved values.
	ConceptName string

	// StartValue is the first value in the range (inclusive) within the referenced concept.
	// This value must exist in the referenced concept's resolved values.
	StartValue string

	// EndValue is the last value in the range (inclusive) within the referenced concept.
	// This value must exist in the referenced concept's resolved values.
	EndValue string
}

// GenerateValues produces the concept values defined by this generator.
//
// This stub satisfies the Generator interface. The actual value generation logic
// will be implemented in Phase C.
//
// Parameters:
//   - concepts: A map of concept names to their resolved definitions, used to
//     look up the referenced concept.
//
// Returns:
//   - nil (placeholder until Phase C implementation).
//   - nil (placeholder until Phase C implementation).
func (c *ConceptRangeGenerator) GenerateValues(concepts map[string]AnalysisConceptDefinition) ([]string, error) {
	// Look up the referenced concept
	sourceConcept, exists := concepts[c.ConceptName]
	if !exists {
		return nil, fmt.Errorf("referenced concept not found: %s", c.ConceptName)
	}

	// Find start and end value positions using the source concept's index
	startIdx, startExists := sourceConcept.index[c.StartValue]
	if !startExists {
		return nil, fmt.Errorf("start value not found: '%s' in concept '%s'", c.StartValue, c.ConceptName)
	}

	endIdx, endExists := sourceConcept.index[c.EndValue]
	if !endExists {
		return nil, fmt.Errorf("end value not found: '%s' in concept '%s'", c.EndValue, c.ConceptName)
	}

	// Validate ordering: start must not come after end
	if startIdx > endIdx {
		return nil, fmt.Errorf("start value '%s' comes after end value '%s' in concept '%s'",
			c.StartValue, c.EndValue, c.ConceptName)
	}

	// Extract values from start to end (inclusive)
	values := make([]string, 0, endIdx-startIdx+1)
	for i := startIdx; i <= endIdx; i++ {
		values = append(values, sourceConcept.ResolvedValues[i].Name)
	}

	return values, nil
}

// AnalysisConceptDefinition contains the analyzed concept information.
//
// This structure represents a fully-processed concept definition, ready for
// validation and code generation. It includes the concept's name, its value
// generators, the resolved list of values, and an index for O(1) value lookup.
//
// For Increment 1, this handles flat concept namespaces with explicit value lists.
// Future increments will add hierarchy support (parent/child relationships),
// conditional values, and range generators.
type AnalysisConceptDefinition struct {
	// ConceptName is the identifier for this concept (e.g., "Country", "Status").
	// This name is used to reference the concept in metrics, aggregators, and
	// other CPL constructs.
	ConceptName string

	ParentConceptName *string

	// InsertionPoint specifies where new values should be inserted relative to
	// existing values for concept extensions. A zero-value InsertionPoint (both
	// BeforeValue and AfterValue empty) indicates this is an initial concept
	// definition, not an extension. When non-zero, this concept is an extension
	// and its values should be inserted at the specified position in the
	// already-defined concept of the same name.
	//
	// This field is populated from the AST's ConceptDefinitionData during
	// EnterAnalyzeConceptScope by reading the InsertionPoint from table.Data.
	InsertionPoint ast.InsertionPoint

	// Generators is the slice of analysis-phase generators for this concept.
	//
	// Each generator produces a set of values that are concatenated to form
	// the complete value list for this concept. Multiple generators allow
	// concepts to be defined piecewise (e.g., combining explicit values with
	// ranges).
	//
	// For Increment 1, only ValuesGenerator is supported.
	Generators []Generator

	// ConditionalValues maps parent concept values to child concept values for
	// conditional specifications.
	//
	// When a child concept is defined conditionally based on a parent concept
	// (e.g., Country[USA] => State=[Values[NY, CA, TX]]), this map records
	// which child values apply for each parent value. The key is the parent
	// value string, and the value is the slice of child concept values that
	// are valid when the parent has that value.
	//
	// Example: For the conditional definition above, the resulting entry is:
	//   ConditionalValues["USA"] = ["NY", "CA", "TX"]
	//
	// This map is populated during analysis of conditional concept blocks
	// and is used during validation and code generation to enforce
	// parent-child value constraints.
	ConditionalValues map[string][]string

	// DefaultValues holds the unconditional (default) values for a child concept.
	//
	// When a child concept has conditional specifications based on a parent
	// concept, but no conditional specification matches a particular parent value,
	// these default values apply for that parent value.
	//
	// Example: If Product=[Values[Widget, Gadget]] and Variant has no conditions
	// matching a specific product, DefaultValues = ["Standard", "Premium"] would
	// be used as the variant values for that product.
	//
	// This slice is populated during analysis when a child concept defines
	// unconditional values alongside conditional specifications, and is used
	// during validation and code generation as the fallback value set.
	DefaultValues []string

	// ResolvedValues is the ordered list of values generated for this concept.
	//
	// This slice is populated during analysis by calling GenerateValues on each
	// generator and concatenating the results in declaration order. The Position
	// field of each AnalysisConceptValueDefinition reflects its index in this slice.
	ResolvedValues []AnalysisConceptValueDefinition

	// index provides O(1) lookup from value name to its position in ResolvedValues.
	//
	// This map is computed during analysis and enables efficient validation of
	// concept value references (e.g., checking if a value exists, finding its
	// position for range operations). The key is the value name, and the value
	// is the index into the ResolvedValues slice.
	//
	// Note: This field is lowercase (unexported) as it's an implementation detail
	// for internal lookup operations.
	index map[string]int

	// Reference to the main analyzer
	analyzer *CPLAnalyzer

	IndentAsSpaces int

	// SourceLocation is the location where the concept was defined in the source file.
	// This is used for error reporting, particularly for duplicate concept detection.
	SourceLocation symboltable.SourceLocation

	// usedInsertionAnchors tracks which anchor+direction pairs have been used
	// by concept extensions to detect duplicate insertions at the same position.
	// The key format is "before:<anchor>" or "after:<anchor>" (e.g., "before:Low").
	// Populated during mergeConceptValues for each extension that is merged.
	usedInsertionAnchors map[string]bool
}

// ContainsValue checks if a value exists in this concept's resolved values.
// Returns true if the value is found, false otherwise.
func (acd *AnalysisConceptDefinition) ContainsValue(value string) bool {
	if acd.index == nil {
		return false
	}
	_, exists := acd.index[value]
	return exists
}

// GetIntRangeBounds returns the start and end bounds if this concept has
// exactly one generator that is an IntRangeGenerator.
// Returns (0, 0, false) if the concept does not have a single IntRangeGenerator.
func (acd *AnalysisConceptDefinition) GetIntRangeBounds() (start, end int, ok bool) {
	if len(acd.Generators) != 1 {
		return 0, 0, false
	}
	gen, ok := acd.Generators[0].(*IntRangeGenerator)
	if !ok {
		return 0, 0, false
	}
	return gen.Start, gen.End, true
}

// BuildIndex rebuilds the internal index map from ResolvedValues.
// This is useful when constructing concept definitions directly for testing.
func (acd *AnalysisConceptDefinition) BuildIndex() {
	if acd.index == nil {
		acd.index = make(map[string]int)
	}
	for i, v := range acd.ResolvedValues {
		acd.index[v.Name] = i
	}
}

// GetValuesForParent returns the child concept values that apply when the
// parent concept has the specified value. If conditional values exist for
// the given parent value, they are returned. Otherwise, DefaultValues is
// returned as a fallback.
//
// Returns nil if neither conditional nor default values exist for the
// specified parent value.
func (acd *AnalysisConceptDefinition) GetValuesForParent(parentValue string) []string {
	if values, exists := acd.ConditionalValues[parentValue]; exists {
		return values
	}
	return acd.DefaultValues
}

// HasConditionalValues returns true if this concept has any conditional
// value specifications (i.e., the ConditionalValues map is non-empty).
func (acd *AnalysisConceptDefinition) HasConditionalValues() bool {
	return len(acd.ConditionalValues) > 0
}

// NewValuesConceptDefinition creates a concept definition with a ValuesGenerator.
// The returned concept has its ResolvedValues and internal index fully populated.
func NewValuesConceptDefinition(name string, values []string) AnalysisConceptDefinition {
	gen := &ValuesGenerator{Values: values}
	resolved := make([]AnalysisConceptValueDefinition, len(values))
	index := make(map[string]int)
	for i, v := range values {
		resolved[i] = AnalysisConceptValueDefinition{Name: v, Position: i}
		index[v] = i
	}
	return AnalysisConceptDefinition{
		ConceptName:    name,
		Generators:     []Generator{gen},
		ResolvedValues: resolved,
		index:          index,
	}
}

// NewIntRangeConceptDefinition creates a concept definition with an IntRangeGenerator.
// The returned concept has its ResolvedValues and internal index fully populated.
// Returns an error if the Int range parameters are invalid.
func NewIntRangeConceptDefinition(name string, start, end, step int) (AnalysisConceptDefinition, error) {
	gen := &IntRangeGenerator{Start: start, End: end, Step: step}
	values, err := gen.GenerateValues(nil)
	if err != nil {
		return AnalysisConceptDefinition{}, err
	}
	resolved := make([]AnalysisConceptValueDefinition, len(values))
	index := make(map[string]int)
	for i, v := range values {
		resolved[i] = AnalysisConceptValueDefinition{Name: v, Position: i}
		index[v] = i
	}
	return AnalysisConceptDefinition{
		ConceptName:    name,
		Generators:     []Generator{gen},
		ResolvedValues: resolved,
		index:          index,
	}, nil
}

func NewAnalysisConceptDefinition(Name string, indentAsSpaces int, analyzer *CPLAnalyzer, location symboltable.SourceLocation) *AnalysisDefinition {
	return &AnalysisDefinition{
		DefinitionType: conceptDefinition,
		ConceptDefinition: &AnalysisConceptDefinition{
			ConceptName:       Name,
			ParentConceptName: nil,
			Generators:        make([]Generator, 0),
			ResolvedValues:    make([]AnalysisConceptValueDefinition, 0),
			IndentAsSpaces:    indentAsSpaces,
			index:             make(map[string]int),
			analyzer:          analyzer,
			SourceLocation:    location,
		},
	}
}

func (ac *AnalysisContext) AddGenerator(g Generator) error {
	analysisConcept, err := ac.Peek()

	if err != nil {
		return fmt.Errorf("Unable to add generator: %v", err)
	}

	if analysisConcept.DefinitionType != conceptDefinition || analysisConcept.ConceptDefinition == nil {
		return fmt.Errorf("Expected a concept definition, got: %v", analysisConcept.DefinitionType)
	}

	conceptDefinition := analysisConcept.ConceptDefinition
	conceptDefinition.Generators = append(conceptDefinition.Generators, g)

	// ConceptRangeGenerators reference other concepts that may not be
	// resolved yet. Defer value generation to ResolveConceptRanges().
	if _, isCRG := g.(*ConceptRangeGenerator); isCRG {
		return nil
	}

	initialResolvedValuesLength := len(conceptDefinition.ResolvedValues)

	generatedValues, err := g.GenerateValues(conceptDefinition.analyzer.GetConcepts())

	if err != nil {
		return fmt.Errorf("Unable to generate values for generator: %v", err)
	}

	for i, v := range generatedValues {
		conceptDefinition.ResolvedValues = append(conceptDefinition.ResolvedValues, AnalysisConceptValueDefinition{
			Name:     v,
			Position: i + initialResolvedValuesLength,
		})
		conceptDefinition.index[v] = i + initialResolvedValuesLength
	}

	return nil
}

// EnterAnalyzeConceptsScope resets concept hierarchy tracking when entering a new concepts section.
// This ensures that parent-child relationships do not incorrectly span across multiple concepts sections.
func EnterAnalyzeConceptsScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	analyzer.conceptAnalyzer.ResetLastConceptName()
	return nil
}

// AnalyzeConceptScope handles the setup for a concepts scope.
//
// In this scope we expect to find an identifier that holds the name of the concept.
// If table.Data contains a ConceptDefinitionData with a non-zero InsertionPoint,
// the InsertionPoint is extracted and stored on the AnalysisConceptDefinition to
// mark this as a concept extension (Increment 6: before/after support).
func EnterAnalyzeConceptScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	// Guard against scopes with no definitions. Concept extensions produce scopes
	// with definitions >= 2 (concept name + anchor identifier from insertion point),
	// so we use < 1 rather than != 1 to allow extensions through.
	if len(table.Definitions) < 1 {
		return nil
	}

	if table.Definitions[0].DefinitionType != symboltable.Identifier {
		return fmt.Errorf("Expected an identifer for concept, got: %s", symboltable.DefinitionType(table.Definitions[0].DefinitionType))
	}

	concept := NewAnalysisConceptDefinition(*table.Definitions[0].Name, table.IndentedSpaceEquivalent, analyzer, table.Definitions[0].Location)

	// Extract InsertionPoint from table.Data if present (set by the parser
	// during ExitConceptExtension for concept extensions with before/after).
	if table.Data != nil {
		if conceptData, ok := table.Data.(*ast.ConceptDefinitionData); ok {
			concept.ConceptDefinition.InsertionPoint = conceptData.InsertionPoint
		}
	}

	return context.Push(concept)
}

// ExitAnalyzeConceptScope handles the completion of a concept scope.
//
// It pops the concept from the analysis context and passes it to AddOrMergeConcept,
// which handles both initial concept definitions and concept extensions (Increment 6).
//
// When the concept scope is a child of ConditionalSpecScope, the function delegates
// to processConditionalSpecChild which reads the ConditionalSpec data (stored in the
// ConceptScope's Data field by ExitConceptLine during parsing) and resolves the
// child concept with conditional values.
//
// The guard uses < 1 rather than != 1 because concept extensions produce scopes
// with definitions >= 2 (concept name + anchor identifier from insertion point),
// so we must allow scopes with more than 1 definition through.
func ExitAnalyzeConceptScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	if len(table.Definitions) < 1 {
		return nil
	}

	concept, err := context.Pop()

	if err != nil {
		return fmt.Errorf("Unable to pop concept: %v", err)
	}

	if concept.DefinitionType != conceptDefinition || concept.ConceptDefinition == nil {
		return fmt.Errorf("Expected a concept definition, got: %v", concept.DefinitionType)
	}

	conceptDef := concept.ConceptDefinition

	// When this concept scope is a child of ConditionalSpecScope, delegate to
	// processConditionalSpecChild to resolve conditional values against the parent.
	if table.Parent != nil && table.Parent.ScopeType == symboltable.ConditionalSpecScope {
		return processConditionalSpecChild(conceptDef, table, analyzer)
	}

	return analyzer.AddOrMergeConcept(conceptDef)
}

// AnalyzeValueGeneratorScope handles the capture of values in a value generator scope.
// AnalyzeValueGeneratorScope expects there to be a bunch of identifiers for the values
// in the definitions.
func AnalyzeValueGeneratorScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	if len(table.Definitions) == 0 {
		return fmt.Errorf("Expected to find values for Values generator, but found none.")
	}

	generator := ValuesGenerator{
		Values: make([]string, 0),
	}

	for _, v := range table.Definitions {
		if v.DefinitionType != symboltable.Identifier {
			return fmt.Errorf("Expected an identifer for value, got: %s", symboltable.DefinitionType(v.DefinitionType))
		}

		if v.Name == nil {
			return fmt.Errorf("Expected an identifer for value, got a Nil name")
		}

		generator.Values = append(generator.Values, *v.Name)
	}

	context.AddGenerator(&generator)

	return nil
}

// AnalyzeIntGeneratorScope handles the capture of an Int range generator scope.
//
// This function extracts the IntRangeGeneratorDef stored in the scope's Data field
// during parsing, creates an IntRangeGenerator, and adds it to the current concept.
//
// The parser stores the validated IntRangeGeneratorDef in scope.Data during
// ExitIntRangeGenerator. If parsing validation failed, Data will be nil.
func AnalyzeIntGeneratorScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	if table.Data == nil {
		return fmt.Errorf("Int generator scope has no data; parsing may have failed")
	}

	intRangeDef, ok := table.Data.(*ast.IntRangeGeneratorDef)
	if !ok {
		return fmt.Errorf("Int generator scope data is not *ast.IntRangeGeneratorDef, got: %T", table.Data)
	}

	generator := IntRangeGenerator{
		Start: intRangeDef.Start,
		End:   intRangeDef.End,
		Step:  intRangeDef.Step,
	}

	return context.AddGenerator(&generator)
}

// insertionAnchorKey builds a tracking key for a given InsertionPoint to detect
// duplicate insertions at the same position. The key format is "before:<anchor>"
// or "after:<anchor>" (e.g., "before:Low", "after:Medium").
func insertionAnchorKey(ip ast.InsertionPoint) string {
	if ip.BeforeValue != "" {
		return "before:" + ip.BeforeValue
	}
	return "after:" + ip.AfterValue
}

// mergeConceptValues merges a concept extension into an existing concept definition.
//
// When a concept extension (same name as an existing concept, with a non-zero
// InsertionPoint) is encountered, this function merges its generators and values
// into the existing concept. It extracts the extension's generated values from
// its ResolvedValues (already populated by AddGenerator during the analysis walk),
// builds an InsertionRequest from the extension's InsertionPoint, and calls
// ComputeValueOrdering to compute the new total value order.
//
// Validation performed:
//   - InsertionPoint must specify exactly one of before or after (not both, not neither).
//   - Duplicate insertions at the same anchor position are detected and rejected.
//   - The anchor value must exist in the existing concept's resolved values.
//
// The existing concept is modified in-place: its ResolvedValues, index,
// Generators, and usedInsertionAnchors are updated to reflect the merged state.
//
// Parameters:
//   - existing: The already-defined concept to extend. Modified in-place on success.
//   - extension: The extension concept with generators and InsertionPoint set.
//     Its ResolvedValues must already be populated (handled by AddGenerator during
//     the analysis walk before this function is called).
//
// Returns:
//   - error if merging fails (e.g., invalid insertion point, duplicate insertion
//     at same position, or the anchor value is not found).
func mergeConceptValues(existing *AnalysisConceptDefinition, extension *AnalysisConceptDefinition) error {
	ip := extension.InsertionPoint
	loc := extension.SourceLocation

	// Validate exactly one of BeforeValue or AfterValue is set
	if ip.BeforeValue == "" && ip.AfterValue == "" {
		return fmt.Errorf("extension must specify before or after (line %d, column %d)",
			loc.Line, loc.Column)
	}
	if ip.BeforeValue != "" && ip.AfterValue != "" {
		return fmt.Errorf("extension must specify exactly one of before or after, not both (line %d, column %d)",
			loc.Line, loc.Column)
	}

	// Detect duplicate insertions at the same anchor position
	key := insertionAnchorKey(ip)
	if existing.usedInsertionAnchors == nil {
		existing.usedInsertionAnchors = make(map[string]bool)
	}
	if existing.usedInsertionAnchors[key] {
		return fmt.Errorf("duplicate insertion at same position '%s' for concept '%s' (line %d, column %d)",
			key, existing.ConceptName, loc.Line, loc.Column)
	}
	existing.usedInsertionAnchors[key] = true

	// Extract new value names from the extension's already-resolved values.
	// These were populated by AddGenerator during the analysis walk.
	newValues := make([]string, len(extension.ResolvedValues))
	for i, v := range extension.ResolvedValues {
		newValues[i] = v.Name
	}

	// Check for duplicate values before merging: ensure none of the extension's
	// new values already exist in the base concept's index. This prevents silent
	// duplicate entries in ResolvedValues and overwrites in the index map.
	for _, newVal := range newValues {
		if _, exists := existing.index[newVal]; exists {
			return fmt.Errorf("duplicate value '%s' in concept extension '%s': value already exists in base concept (extension line %d, column %d)",
				newVal, existing.ConceptName, loc.Line, loc.Column)
		}
	}

	// Extract base value names from the existing concept's ResolvedValues
	baseValues := make([]string, len(existing.ResolvedValues))
	for i, v := range existing.ResolvedValues {
		baseValues[i] = v.Name
	}

	// Build the InsertionRequest and compute the new value ordering
	insertions := []InsertionRequest{
		{Position: ip, Values: newValues},
	}

	ordered, err := ComputeValueOrdering(baseValues, insertions)
	if err != nil {
		return fmt.Errorf("invalid insertion for concept '%s' (line %d, column %d): %w",
			existing.ConceptName, loc.Line, loc.Column, err)
	}

	// Update the existing concept with the new ordered values and rebuilt index
	existing.ResolvedValues = ordered
	existing.index = make(map[string]int)
	for i, v := range ordered {
		existing.index[v.Name] = i
	}

	// Append the extension's generators to the existing concept's Generators list
	existing.Generators = append(existing.Generators, extension.Generators...)

	return nil
}

// InsertionRequest pairs an insertion point from the AST with the new values
// to insert at that position. This separates the positional information
// (before/after) from the values being inserted.
type InsertionRequest struct {
	Position ast.InsertionPoint
	Values   []string
}

// ComputeValueOrdering computes the final ordered list of concept values
// when extensions with before/after insertion points are applied.
//
// It takes the base values from an initial concept declaration and a list
// of insertion requests from concept extensions, and produces a fully ordered
// slice of AnalysisConceptValueDefinition values with correct Position indices.
//
// The insertion requests are processed in order. Each request must specify
// exactly one of BeforeValue or AfterValue in its Position field. The
// referenced value must exist in the ordered list (including values added
// by prior insertions).
//
// Parameters:
//   - baseValues: The ordered list of value names from the initial concept declaration.
//   - insertions: A slice of InsertionRequest structs specifying where new values
//     should be inserted (before or after existing values). Processed in order.
//
// Returns:
//   - A slice of AnalysisConceptValueDefinition with computed positions.
//   - An error if an insertion point references a non-existent value or if
//     an insertion point is invalid (neither before nor after specified, or both).
func ComputeValueOrdering(
	baseValues []string,
	insertions []InsertionRequest) ([]AnalysisConceptValueDefinition, error) {

	// Step 1: Copy base values into an ordered slice
	ordered := make([]string, len(baseValues))
	copy(ordered, baseValues)

	// Step 2: Process each insertion request in order
	for _, ins := range insertions {
		var insertPos int

		// Validate exactly one of BeforeValue or AfterValue is set
		if ins.Position.BeforeValue != "" && ins.Position.AfterValue != "" {
			return nil, fmt.Errorf("insertion must specify exactly one of before or after, not both")
		}

		if ins.Position.BeforeValue != "" {
			// Find position of the "before" anchor value
			pos, found := findValue(ordered, ins.Position.BeforeValue)
			if !found {
				return nil, fmt.Errorf("'before' value not found: %s", ins.Position.BeforeValue)
			}
			insertPos = pos
		} else if ins.Position.AfterValue != "" {
			// Find position after the "after" anchor value
			pos, found := findValue(ordered, ins.Position.AfterValue)
			if !found {
				return nil, fmt.Errorf("'after' value not found: %s", ins.Position.AfterValue)
			}
			insertPos = pos + 1
		} else {
			return nil, fmt.Errorf("insertion must specify before or after")
		}

		// Insert the new values at the computed position
		ordered = insertValues(ordered, insertPos, ins.Values)
	}

	// Step 3: Convert to AnalysisConceptValueDefinition slice with correct Position indices
	result := make([]AnalysisConceptValueDefinition, len(ordered))
	for i, val := range ordered {
		result[i] = AnalysisConceptValueDefinition{Name: val, Position: i}
	}

	return result, nil
}

// findValue returns the index of a value in the ordered slice, or -1 and false if not found.
func findValue(ordered []string, target string) (int, bool) {
	for i, v := range ordered {
		if v == target {
			return i, true
		}
	}
	return -1, false
}

// insertValues inserts a slice of values into the ordered slice at the given position.
func insertValues(ordered []string, pos int, values []string) []string {
	if len(values) == 0 {
		return ordered
	}
	// Create a new slice with enough capacity
	result := make([]string, 0, len(ordered)+len(values))
	result = append(result, ordered[:pos]...)
	result = append(result, values...)
	result = append(result, ordered[pos:]...)
	return result
}

// AnalyzeConceptRangeGeneratorScope handles the capture of a concept range generator scope.
//
// This function extracts the ConceptRangeGeneratorDef stored in the scope's Data field
// during parsing, creates a ConceptRangeGenerator, and adds it to the current concept.
//
// Unlike ValuesGenerator and IntRangeGenerator, the ConceptRangeGenerator defers value
// generation to ResolveConceptRanges() because it references another concept that may
// not have been processed yet. AddGenerator recognizes ConceptRangeGenerators and
// skips the immediate GenerateValues call.
//
// The parser stores the validated ConceptRangeGeneratorDef in scope.Data during
// ExitConceptRangeGenerator. If parsing validation failed, Data will be nil.
func AnalyzeConceptRangeGeneratorScope(table *symboltable.SymbolTable, context *AnalysisContext, analyzer *CPLAnalyzer) error {
	if table.Data == nil {
		return fmt.Errorf("concept range generator scope has no data; parsing may have failed")
	}

	conceptRangeDef, ok := table.Data.(*ast.ConceptRangeGeneratorDef)
	if !ok {
		return fmt.Errorf("concept range generator scope data is not *ast.ConceptRangeGeneratorDef, got: %T", table.Data)
	}

	generator := ConceptRangeGenerator{
		ConceptName: conceptRangeDef.ConceptName,
		StartValue:  conceptRangeDef.StartValue,
		EndValue:    conceptRangeDef.EndValue,
	}

	return context.AddGenerator(&generator)
}

// ResolveConditionalValues resolves conditional specifications for a child concept
// by validating parent values and building parent-specific child value mappings.
//
// It processes each conditional specification from the child's parser data,
// validates that the referenced parent value exists in the parent concept's
// resolved values, creates generator instances from the spec data, expands
// the generators to produce child values, and populates the ConditionalValues
// map keyed by parent value.
//
// Default values (unconditional specs) are stored in DefaultValues and also
// included in the unified value list.
//
// Parameters:
//   - childData: The parser-level concept definition data containing
//     conditional specifications and default values.
//   - parentConcept: The already-analyzed parent concept definition used
//     to validate parent value references.
//   - concepts: The map of all analyzed concepts, needed to resolve
//     ConceptRangeGenerator references in conditional specs.
//
// Returns:
//   - A new AnalysisConceptDefinition with ConditionalValues, DefaultValues,
//     and a unified ResolvedValues list if successful.
//   - An error if a parent value referenced in a conditional spec does not
//     exist in the parent concept, or if value generation fails.
func ResolveConditionalValues(
	childData *ast.ConceptDefinitionData,
	parentConcept *AnalysisConceptDefinition,
	concepts map[string]AnalysisConceptDefinition) (*AnalysisConceptDefinition, error) {

	// Validate inputs
	if childData == nil {
		return nil, fmt.Errorf("child concept data is nil")
	}
	if parentConcept == nil {
		return nil, fmt.Errorf("parent concept is nil")
	}

	result := &AnalysisConceptDefinition{
		ConceptName:       childData.Name,
		ConditionalValues: make(map[string][]string),
	}

	// Set parent concept name
	parentName := parentConcept.ConceptName
	result.ParentConceptName = &parentName

	// Process conditional specifications: validate each parent value exists
	// in the parent concept and expand the child values based on generator type.
	for _, spec := range childData.ConditionalSpecs {
		// Validate that the parent value exists in the parent concept
		if !parentConcept.ContainsValue(spec.ParentValue) {
			return nil, fmt.Errorf("parent value '%s' not found in parent concept '%s' (conditional concept '%s' at line %d, column %d)",
				spec.ParentValue, parentConcept.ConceptName, childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
		}

		// Expand values based on generator type
		var values []string
		switch spec.GeneratorType {
		case ast.ValuesGenerator:
			values = spec.Values
		case ast.IntRangeGenerator:
			if spec.RangeBounds == nil {
				return nil, fmt.Errorf("conditional spec for concept '%s' has IntRangeGenerator but no RangeBounds (line %d, column %d)",
					childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			start, err := strconv.Atoi(spec.RangeBounds.Start)
			if err != nil {
				return nil, fmt.Errorf("invalid start value '%s' in Int range conditional spec for concept '%s' (line %d, column %d)",
					spec.RangeBounds.Start, childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			end, err := strconv.Atoi(spec.RangeBounds.End)
			if err != nil {
				return nil, fmt.Errorf("invalid end value '%s' in Int range conditional spec for concept '%s' (line %d, column %d)",
					spec.RangeBounds.End, childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			step := spec.RangeBounds.Step
			if step == 0 {
				step = 1
			}
			genValues, err := (&IntRangeGenerator{Start: start, End: end, Step: step}).GenerateValues(nil)
			if err != nil {
				return nil, fmt.Errorf("failed to expand Int range in conditional spec for concept '%s': %w",
					childData.Name, err)
			}
			values = genValues
		case ast.ConceptRangeGenerator:
			if spec.RangeBounds == nil {
				return nil, fmt.Errorf("conditional spec for concept '%s' has ConceptRangeGenerator but no RangeBounds (line %d, column %d)",
					childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			if concepts == nil {
				return nil, fmt.Errorf("cannot resolve Concept range in conditional spec for concept '%s': concepts map is nil",
					childData.Name)
			}
			sourceName := spec.SourceConceptName
			if sourceName == "" {
				return nil, fmt.Errorf("conditional spec for concept '%s' has ConceptRangeGenerator but no SourceConceptName (line %d, column %d)",
					childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			_, sourceExists := concepts[sourceName]
			if !sourceExists {
				return nil, fmt.Errorf("source concept '%s' not found for Concept range in conditional spec for '%s' (line %d, column %d)",
					sourceName, childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
			}
			genValues, err := (&ConceptRangeGenerator{
				ConceptName: sourceName,
				StartValue:  spec.RangeBounds.Start,
				EndValue:    spec.RangeBounds.End,
			}).GenerateValues(concepts)
			if err != nil {
				return nil, fmt.Errorf("failed to expand Concept range in conditional spec for '%s': %w",
					childData.Name, err)
			}
			values = genValues
		default:
			return nil, fmt.Errorf("unsupported generator type %d in conditional spec for concept '%s' (line %d, column %d)",
				spec.GeneratorType, childData.Name, childData.SourceLocation.Line, childData.SourceLocation.Column)
		}
		result.ConditionalValues[spec.ParentValue] = values
	}

	// Process default values (unconditional fallback)
	if len(childData.DefaultValues) > 0 {
		result.DefaultValues = childData.DefaultValues
	}

	// Build the unified value list: conditional values first (in spec order),
	// then default values, with deduplication between the two sets.
	seen := make(map[string]bool)
	var resolvedValues []AnalysisConceptValueDefinition

	// Add conditional values first
	for _, spec := range childData.ConditionalSpecs {
		expandedValues := result.ConditionalValues[spec.ParentValue]
		for _, val := range expandedValues {
			if !seen[val] {
				seen[val] = true
				resolvedValues = append(resolvedValues, AnalysisConceptValueDefinition{
					Name:     val,
					Position: len(resolvedValues),
				})
			}
		}
	}

	// Add default values (deduplicated against conditional values)
	for _, val := range childData.DefaultValues {
		if !seen[val] {
			seen[val] = true
			resolvedValues = append(resolvedValues, AnalysisConceptValueDefinition{
				Name:     val,
				Position: len(resolvedValues),
			})
		}
	}

	result.ResolvedValues = resolvedValues
	result.BuildIndex()

	return result, nil
}

// processConditionalSpecChild processes a child concept scope that lives inside
// a ConditionalSpecScope. It reads the ConditionalSpec data from the ConceptScope's
// Data field (stored there by ExitConditionalSpec), extracts the parent concept
// name from the parent ConditionalSpecScope's definitions, resolves the parent
// concept from the analyzer, calls ResolveConditionalValues to validate parent
// values and build the ConditionalValues map, merges the resolved data into the
// child concept definition, and calls AddOrMergeConcept to add or merge the child
// concept into the analyzer.
//
// The data flow is:
//  1. Read ConceptDefinitionData from table.Data (set by ExitConceptLine during parsing)
//  2. Clear DefaultValues from the parser data (they were a temporary container)
//  3. Resolve parent concept name from table.Parent.Definitions (set by ExitConditionalSpec)
//  4. Look up parent concept in the analyzer
//  5. Call ResolveConditionalValues to validate parent values and expand generators
//  6. Merge ConditionalValues, DefaultValues, ResolvedValues into conceptDef
//  7. Clear walker-added Generators (ResolveConditionalValues handles value expansion)
//  8. If concept already exists in analyzer, merge conditional values and transfer
//     existing ResolvedValues to DefaultValues for fallback; otherwise add as new.
func processConditionalSpecChild(
	conceptDef *AnalysisConceptDefinition,
	table *symboltable.SymbolTable,
	analyzer *CPLAnalyzer) error {

	// Read conditional spec data from table.Data
	if table.Data == nil {
		return nil // no data, nothing to process
	}
	conceptData, ok := table.Data.(*ast.ConceptDefinitionData)
	if !ok || len(conceptData.ConditionalSpecs) == 0 {
		return nil
	}

	// The parser (ExitConceptLine) stores ALL concept values in DefaultValues
	// as a temporary container, and ExitConditionalSpec copies them to
	// ConditionalSpecs[].Values. After consuming the ConditionalSpecs, clear
	// DefaultValues so GetValuesForParent won't incorrectly return conditional
	// values as defaults for non-matching parent values. The conditional-spec
	// guard at the top of this function (len(conceptData.ConditionalSpecs) == 0)
	// prevents re-entry, so table.Data does not need to be nilled.
	conceptData.DefaultValues = nil

	// Resolve parent concept name from the ConditionalSpecScope.
	// The ConditionalSpecScope (table.Parent) stores the parent concept
	// name as its first definition (e.g., "Country" in Country[USA] => ...).
	// Table structure:
	//   table = ConceptScope (e.g., State)
	//   table.Parent = ConditionalSpecScope (Definitions=[0:Country][1:USA])
	if table.Parent == nil {
		return fmt.Errorf("cannot resolve parent concept for conditional spec")
	}
	if len(table.Parent.Definitions) < 1 || table.Parent.Definitions[0].Name == nil {
		return fmt.Errorf("conditional spec scope has no parent concept name")
	}
	parentName := *table.Parent.Definitions[0].Name

	// Find parent concept in analyzer
	parentConcept := analyzer.GetConcept(parentName)
	if parentConcept.ConceptName == "" {
		return fmt.Errorf("parent concept '%s' not found", parentName)
	}

	// Set parent relationship on child concept
	conceptDef.ParentConceptName = &parentName

	// Build ConceptDefinitionData with ConditionalSpecs for ResolveConditionalValues
	resolved, err := ResolveConditionalValues(conceptData, &parentConcept, analyzer.GetConcepts())
	if err != nil {
		return fmt.Errorf("failed to resolve conditional values for concept '%s': %w", conceptDef.ConceptName, err)
	}

	// Merge resolved data into the child concept definition
	conceptDef.ConditionalValues = resolved.ConditionalValues
	conceptDef.DefaultValues = resolved.DefaultValues
	conceptDef.ResolvedValues = resolved.ResolvedValues
	conceptDef.BuildIndex()

	// Clear generators that the analysis walker may have added while visiting
	// child scopes (e.g., ConceptRangeGenerator from ConceptGeneratorScope).
	// processConditionalSpecChild has fully resolved all values via
	// ResolveConditionalValues, so any walker-added generators are duplicates.
	conceptDef.Generators = nil

	// Merge into existing concept if it already exists (e.g., Region defined as
	// a regular concept with default values, then extended via conditional specs).
	// If it does not exist, add it as a new concept.
	if analyzer.HasConcept(conceptDef.ConceptName) {
		existingConcept := analyzer.GetConcept(conceptDef.ConceptName)
		// Merge conditional values into the existing concept
		if existingConcept.ConditionalValues == nil {
			existingConcept.ConditionalValues = make(map[string][]string)
		}
		for k, v := range conceptDef.ConditionalValues {
			existingConcept.ConditionalValues[k] = v
		}

		// When an existing unconditional concept is extended with conditional
		// values, transfer the existing concept's ResolvedValues to DefaultValues
		// so that GetValuesForParent can fall back to them for parent values
		// that don't have a conditional match.
		if existingConcept.DefaultValues == nil {
			defaultVals := make([]string, len(existingConcept.ResolvedValues))
			for i, v := range existingConcept.ResolvedValues {
				defaultVals[i] = v.Name
			}
			existingConcept.DefaultValues = defaultVals
		}

		// Merge resolved values: add only values not already present
		for _, newVal := range conceptDef.ResolvedValues {
			if !existingConcept.ContainsValue(newVal.Name) {
				existingConcept.ResolvedValues = append(existingConcept.ResolvedValues, newVal)
				existingConcept.index[newVal.Name] = len(existingConcept.ResolvedValues) - 1
			}
		}
		// Set parent relationship if not already set
		if existingConcept.ParentConceptName == nil && conceptDef.ParentConceptName != nil {
			existingConcept.ParentConceptName = conceptDef.ParentConceptName
		}
		analyzer.SetConcept(conceptDef.ConceptName, existingConcept)
		return nil
	}
	return analyzer.AddOrMergeConcept(conceptDef)
}
