// ExitIndent is called when exiting the indent production.
func (l *CPLListener) ExitIndent(ctx *antlr.IndentContext) {
	current, err := l.symbolStack.Peek()

	raw_indent := ctx.GetStart().GetText()

	// Convert tabs to spaces
	spaces := strings.ReplaceAll(raw_indent, "\t", strings.Repeat(" ", symboltable.SpacesPerTab))

	// Calculate the number of spaces
	current.IndentedSpaceEquivalent += len(spaces)

	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error entering indent processing: %w", err))
		return
	}

	l.logExit("Indent", &ctx.BaseParserRuleContext)
}

// EnterArithmeticFactor is called when entering an arithmetic factor.
// For parenthesized sub-expressions (LPAREN arithmeticExpr RPAREN), pushes a
// child TempScope to isolate the sub-expression's postfix definitions.
func (l *CPLListener) EnterArithmeticFactor(ctx *antlr.ArithmeticFactorContext) {
	if ctx.LPAREN() == nil {
		return
	}
	current, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error entering paren: %w", err))
		return
	}
	l.symbolStack.Push(current.AddChild(symboltable.TempScope))
}

// ExitArithmeticFactor is called when exiting an arithmetic factor.
// Handles NUMBER literals, parenthesized sub-expression merging, and the
// POW operator for exponentiation.
func (l *CPLListener) ExitArithmeticFactor(ctx *antlr.ArithmeticFactorContext) {
	// For parenthesized expressions: pop the child TempScope pushed by
	// EnterArithmeticFactor, merge defs back, and remove the transient child
	// scope from the parent so it does not remain in the symbol table tree.
	if ctx.LPAREN() != nil {
		childScope, err := l.symbolStack.Pop()
		if err != nil {
			l.AddError(fmt.Errorf("symbol stack error popping paren scope: %w", err))
			return
		}
		parentScope, err := l.symbolStack.Peek()
		if err != nil {
			l.AddError(fmt.Errorf("symbol stack error peeking after paren scope: %w", err))
			return
		}
		parentScope.Definitions = append(parentScope.Definitions, childScope.Definitions...)
		for i, c := range parentScope.Children {
			if c == childScope {
				parentScope.Children = append(parentScope.Children[:i], parentScope.Children[i+1:]...)
				break
			}
		}
		return
	}

	if !l.shouldPushExpressionDefs() {
		return
	}

	currentScope, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error in ExitArithmeticFactor: %w", err))
		return
	}

	// NUMBER literal
	if ctx.NUMBER() != nil {
		numberText := ctx.NUMBER().GetText()
		numVal, err := strconv.ParseFloat(numberText, 64)
		if err != nil {
			l.AddError(fmt.Errorf("invalid number literal: %s", numberText))
			return
		}
		err = currentScope.DefineWithData(
			nil,
			symboltable.NumberDefinition,
			l.makeSourceLocation(ctx.NUMBER().GetSymbol()),
			symboltable.FloatData{Value: numVal},
		)
		if err != nil {
			l.AddError(fmt.Errorf("error defining number in ExitArithmeticFactor: %w", err))
		}
	}

	// POW operator for exponentiation
	if ctx.POW() != nil {
		l.pushOperatorDef(
			ctx.POW().GetSymbol(),
			OpPower,
			symboltable.PowerOperatorDefinition,
			l.makeSourceLocation(ctx.POW().GetSymbol()),
		)
	}
}

// ExitArithmeticExpr is called when exiting an arithmetic expression.
// Pushes PlusOperatorDefinition or MinusOperatorDefinition based on the operator present.
func (l *CPLListener) ExitArithmeticExpr(ctx *antlr.ArithmeticExprContext) {
	if !l.shouldPushExpressionDefs() {
		return
	}

	currentScope, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error in ExitArithmeticExpr: %w", err))
		return
	}

	var defType symboltable.DefinitionType
	var opType OperatorType
	switch {
	case ctx.PLUS() != nil:
		defType = symboltable.PlusOperatorDefinition
		opType = OpPlus
	case ctx.MINUS() != nil:
		defType = symboltable.MinusOperatorDefinition
		opType = OpMinus
	default:
		return
	}

	err = currentScope.DefineWithData(
		nil,
		defType,
		l.makeSourceLocation(ctx.GetStart()),
		ParserOperator{Operator: opType},
	)
	if err != nil {
		l.AddError(fmt.Errorf("error defining operator in ExitArithmeticExpr: %w", err))
	}
}

