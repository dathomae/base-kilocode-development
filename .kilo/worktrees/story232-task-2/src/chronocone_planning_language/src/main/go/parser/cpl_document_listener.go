// EnterIdentifier is called when entering an identifier node.
func (l *CPLListener) EnterIdentifier(ctx *antlr.IdentifierContext) {
	l.logEnter("Identifier", &ctx.BaseParserRuleContext)

	current, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error entering identifier: %w", err))
		return
	}

	if ctx.GetStart() != nil {
		// Skip identifiers in expression-accumulating scopes; they are
		// captured by ExitPrimaryExpr with Data set to the identifier text.
		if !l.shouldPushExpressionDefs() {
			// Lookups are flat: identifiers inside lookup declarations are
			// extracted by ExitLookupDeclaration into ParserLookupDefinition.
			// Do not add raw Identifier definitions to LookupsScope.
			if current.ScopeType == symboltable.LookupsScope {
				return
			}
			identifier := ctx.GetStart().GetText()
			_ = current.Define(&identifier, symboltable.Identifier, l.makeSourceLocation(ctx.GetStart()))
		}
	}

}

// ExitIdentifier is called when exiting an identifier node.
// It extracts the identifier text and logs it. Context is provided by
// the symbol table stack in Enter/Exit methods.
//
// Error Handling:
// When ctx.IDENTIFIER() is nil, this indicates a semantic error where an
// identifier was expected but not found during parsing. In this case, an
// error should be added via AddError with the following context:
//   - Line and column information (if available from the context)
//   - Descriptive message indicating an identifier was expected
//
// Example error scenarios:
//   - Type definition missing type name identifier
//   - Type reference missing type name identifier
func (l *CPLListener) ExitIdentifier(ctx *antlr.IdentifierContext) {
	l.logExit("Identifier", &ctx.BaseParserRuleContext)

	if !l.shouldPushExpressionDefs() {
		return
	}

	// Only push UnitReferenceDefinition for identifiers that appear as
	// arithmetic expression operands (children of arithmeticFactor).
	// Identifiers inside primaryExpr are handled by ExitPrimaryExpr for
	// the conditional expression chain. All other identifiers (metric names,
	// input names, etc.) are handled by their respective exit methods.
	//
	// GRAMMAR COUPLING NOTE:
	// The type assertion to *antlr.ArithmeticFactorContext below distinguishes
	// identifiers used as arithmetic expression operands from identifiers used
	// in other contexts (e.g., metric names, input names). This type is
	// generated by ANTLR from the arithmeticFactor rule in
	// ChronoconePlanningLanguage.g4. If that rule is renamed, restructured, or
	// the generated context type name changes, this assertion must be updated
	// accordingly or unit references inside arithmetic expressions will not be
	// captured.
	if _, ok := ctx.GetParent().(*antlr.ArithmeticFactorContext); !ok {
		return
	}

	if ctx.GetStart() != nil {
		identifierText := ctx.GetStart().GetText()
		currentScope, err := l.symbolStack.Peek()
		if err != nil {
			l.AddError(fmt.Errorf("symbol stack error in ExitIdentifier: %w", err))
			return
		}
		err = currentScope.DefineWithData(
			nil, // anonymous definition (postfix position encodes operand identity)
			symboltable.UnitReferenceDefinition,
			l.makeSourceLocation(ctx.GetStart()),
			ParserUnitReference{Name: identifierText},
		)
		if err != nil {
			l.AddError(fmt.Errorf("error defining unit reference in ExitIdentifier: %w", err))
		}
	}
}

// EnterValue is called when entering a value node.
// It extracts the value text and stores it in the current symbol table scope.
//
// This handles IDENTIFIER, VALUE, and INTEGER tokens that appear in
// concept value lists (e.g., Values[USA, 2024, 2024A]).
func (l *CPLListener) EnterValue(ctx *antlr.ValueContext) {
	l.logEnter("Value", &ctx.BaseParserRuleContext)

	current, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error entering value: %w", err))
		return
	}

	if ctx.GetStart() != nil {
		valueText := ctx.GetStart().GetText()
		_ = current.Define(&valueText, symboltable.Identifier, l.makeSourceLocation(ctx.GetStart()))
	}
}

