// ExitFnCall is called when exiting a function call expression.
// If the current scope is an expression-accumulating scope, it pushes the
// argument identifiers followed by the function name as Identifier definitions
// in postfix order.
func (l *CPLListener) ExitFnCall(ctx *antlr.FnCallContext) {
	if !l.shouldPushExpressionDefs() {
		return
	}

	currentScope, err := l.symbolStack.Peek()
	if err != nil {
		l.AddError(fmt.Errorf("symbol stack error in ExitFnCall: %w", err))
		return
	}

	// Push argument identifiers first (postfix order: operands before operator)
	if identifierList := ctx.IdentifierList(); identifierList != nil {
		for _, ident := range identifierList.AllIdentifier() {
			err = currentScope.DefineWithData(
				nil,
				symboltable.Identifier,
				l.makeSourceLocation(ident.GetStart()),
				symboltable.StringData{Value: ident.GetText()},
			)
			if err != nil {
				l.AddError(fmt.Errorf("error defining fnCall argument: %w", err))
			}
		}
	}

	// Push function name
	if fnIdent := ctx.Identifier(); fnIdent != nil {
		fnName := fnIdent.GetText()
		err = currentScope.DefineWithData(
			nil,
			symboltable.Identifier,
			l.makeSourceLocation(fnIdent.GetStart()),
			symboltable.StringData{Value: fnName},
		)
		if err != nil {
			l.AddError(fmt.Errorf("error defining fnCall name: %w", err))
		}
	}
}
