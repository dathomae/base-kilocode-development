package synthesis

import (
	"strconv"
	"strings"
)

// ============================================================================
// Task 1a Decision: NO-GO on text/template for CPL codegen
// ============================================================================
//
// During Story225 Task 1a, we prototyped text/template for buildMainImports (import generation).
// The template successfully produced byte-identical output for the chosen target,
// but the migration was deemed a NO-GO for broader adoption. Here's why:
//
// 1. ESCAPING BURDEN: Go source code contains heavy use of quotes (%q), backticks,
//    braces ({, }), and template directive characters. Template strings require
//    extensive escaping that makes them harder to read than the current strings.Builder
//    approach. For example, `fmt.Sprintf("%q", name)` inside a template becomes
//    `fmt.Sprintf(\"%q\", {{.Name}})` which is error-prone.
//
// 2. LOSS OF DETERMINISTIC ORDERING: Map iteration in templates is nondeterministic.
//    The current codegen relies on sort.Strings() before iterating maps to produce
//    deterministic output (critical for testing and reproducibility). Templates
//    cannot sort within the template — this must be done before passing data, which
//    means the template is no longer self-contained and the sorting logic still
//    lives in Go code alongside the template.
//
// 3. LOSS OF EXPRESSIVENESS: The current codegen uses Go control flow (if/switch)
//    to conditionally emit code blocks. Templates require the same conditionals
//    but in template syntax, which reduces readability. Functions like
//    generateInputLoadingCode use complex switch statements over driver parameter
//    types — converting these to template functions would scatter the logic across
//    Go code (template functions) and template text.
//
// 4. DEBUGGING OVERHEAD: Template parse errors are runtime errors, not compile-time.
//    The current strings.Builder approach is pure Go and benefits from compile-time
//    type checking. Template errors only surface when the template is executed,
//    making iteration slower.
//
// 5. MIXED ABSTRACTION: The codegen delegates to other packages (transformer,
//    connector) for sub-components (Compute, Cleanup, connector loaders, metric
//    compute functions). These sub-components return pre-built strings. Mixing
//    template-based and string-based generation in the same function creates
//    an inconsistent abstraction that is harder to maintain than pure strings.Builder.
//
// 6. ZERO COMPLEXITY REDUCTION: For the prototype target (buildMainImports),
//    the template version was 18 lines of template + 15 lines of Go setup vs. 22
//    lines of pure Go in the current approach. The net complexity is approximately
//    equal, but the template version introduces a new language and requires
//    engineers to context-switch between Go and template syntax.
//
// MIGRATION PLAN for Task 1b:
//   Instead of text/template, Task 1b will adopt the GeneratedProgram struct as the
//   intermediate representation. This struct captures program structure (imports,
//   variables, functions) in a typed form, enabling:
//   - Structured testing (verify imports, variables independently)
//   - Cleaner separation of program construction from rendering
//   - No new language dependency
//   - Compile-time type safety
//
// The current GenerateMainFunction will be refactored into two phases:
//   1. Build a GeneratedProgram struct from SynthesisInput
//   2. Render the GeneratedProgram to a Go source string
//
// This preserves the existing strings.Builder rendering but adds the structural
// layer that was the primary goal of this refactoring phase.
// ============================================================================

// GeneratedProgram holds the structured representation of a synthesized Go
// program. Instead of building strings incrementally with strings.Builder,
// program parts are collected into typed fields. This enables:
//   - Independent testing of imports, variables, and functions
//   - Cleaner separation of program construction from code rendering
//   - Deterministic output through sorted field iteration
//
// For the main program (generated by GenerateMainFunction), sub-component
// code from external packages (transformer.TransformMetric,
// connector.GenerateConnectorLoaders, etc.) is stored in RawSourceBeforeMain
// and emitted as-is between the structured variables and the main function.
type GeneratedProgram struct {
	PackageName string
	Imports     []ImportDecl
	Variables   []VariableDecl
	Functions   []FunctionDecl

	// RawSourceBeforeMain contains raw Go source code strings from external
	// code generators (transformer, connector) that are emitted after
	// structured variables and functions but before the main function.
	// Each entry is a complete Go code fragment (variable declaration,
	// function declaration, etc.) with its own trailing newline.
	RawSourceBeforeMain []string
}

// ImportDecl represents a single Go import declaration.
type ImportDecl struct {
	Alias string // "" for regular imports, non-empty for aliased imports (e.g. "cplio")
	Path  string // Full import path
}

// VariableDecl represents a package-level variable declaration with its
// Go source representation.
type VariableDecl struct {
	Name    string // Variable name
	Type    string // Go type expression (e.g. "map[string][]string")
	Value   string // Go source representation of the value
	Comment string // Optional doc comment (without // prefix)
}

// FunctionDecl represents a complete function declaration.
type FunctionDecl struct {
	Name    string // Function name
	Params  string // Parameter list (e.g. "architecture *cplio.ArchitectureSpecification")
	Returns string // Return type(s) (e.g. "error", "(string, error)")
	Body    string // Function body Go source
	Comment string // Optional doc comment (without // prefix)
}

// RenderMainSource renders the GeneratedProgram as a complete Go source string
// using the format expected by GenerateMainFunction output. Variables and
// functions are emitted in declaration order. RawSourceBeforeMain entries
// are emitted after all structured variables and functions. Imports are
// rendered in declaration order (matching the buildMainImports
// ordering).
//
// This renderer produces byte-identical output to the pre-refactoring
// GenerateMainFunction for the same program structure.
//
// Returns:
//   - string: The rendered Go source code.
func (p *GeneratedProgram) RenderMainSource() string {
	var sb strings.Builder

	// Package declaration
	sb.WriteString("package ")
	sb.WriteString(p.PackageName)
	sb.WriteString("\n\n")

	// Import block — rendered in declaration order
	if len(p.Imports) > 0 {
		sb.WriteString("import (\n")
		for _, imp := range p.Imports {
			if imp.Alias != "" {
				sb.WriteString("\t")
				sb.WriteString(imp.Alias)
				sb.WriteString(" ")
				sb.WriteString(strconv.Quote(imp.Path))
				sb.WriteString("\n")
			} else {
				sb.WriteString("\t")
				sb.WriteString(strconv.Quote(imp.Path))
				sb.WriteString("\n")
			}
		}
		sb.WriteString(")\n")
	}

	// Emit an additional newline after imports for consistent formatting.
	sb.WriteString("\n")

	// Package-level variables (conceptValues, metricNames, controller, inputs)
	for _, v := range p.Variables {
		if v.Comment != "" {
			sb.WriteString("// ")
			sb.WriteString(v.Comment)
			sb.WriteString("\n")
		}
		sb.WriteString("var ")
		sb.WriteString(v.Name)
		if v.Type != "" {
			sb.WriteString(" ")
			sb.WriteString(v.Type)
		}
		if v.Value != "" {
			sb.WriteString(" = ")
			sb.WriteString(v.Value)
		}
		sb.WriteString("\n\n")
	}

	// Structured functions (e.g., Setup)
	for _, fn := range p.Functions {
		if fn.Comment != "" {
			sb.WriteString("// ")
			sb.WriteString(fn.Comment)
			sb.WriteString("\n")
		}
		sb.WriteString("func ")
		sb.WriteString(fn.Name)
		sb.WriteString("(")
		sb.WriteString(fn.Params)
		sb.WriteString(")")
		if fn.Returns != "" {
			sb.WriteString(" ")
			sb.WriteString(fn.Returns)
		}
		sb.WriteString(" {\n")
		sb.WriteString(fn.Body)
		sb.WriteString("}\n\n")
	}

	// Raw source from sub-component code generators
	// (transformer.GenerateComputeFunction, GenerateCleanupFunction,
	//  GenerateConnectorMetadataMap, connector.GenerateConnectorLoaders,
	//  transformer.TransformMetric calls)
	//
	// Each entry in RawSourceBeforeMain must include its own trailing newline.
	// Callers (GenerateMainFunction, etc.) are responsible for ensuring all
	// raw source strings end with "\n" so that the generated output is a valid
	// Go source file without run-on lines.
	for _, raw := range p.RawSourceBeforeMain {
		sb.WriteString(raw)
	}

	return sb.String()
}
